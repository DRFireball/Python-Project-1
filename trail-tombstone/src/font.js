  // Typographic punctuation people paste in from phones.
  const ALIAS = {
    '‘': "'", '’': "'", '“': '"', '”': '"',
    '–': '-', '—': '-', '…': '...', ' ': ' ',
  };

  const GLYPH_W = 5;
  const GLYPH_H = 7;
  const ADVANCE = 6;
  const LINE_H = 9;

  const glyphs = {};
  for (const ch of Object.keys(G)) {
    glyphs[ch] = G[ch].split('|').map((row) => Array.from(row, (c) => c === '#'));
  }

  function normalize(text) {
    let out = '';
    for (const ch of String(text == null ? '' : text)) out += ALIAS[ch] != null ? ALIAS[ch] : ch;
    return out;
  }

  function glyphFor(ch) {
    return glyphs[ch] || glyphs['?'];
  }

  /** Width in pixels of a single line at the given scale. */
  function measure(text, scale) {
    const s = scale || 1;
    const n = Array.from(normalize(text)).length;
    return n === 0 ? 0 : (n * ADVANCE - 1) * s;
  }

  /**
   * Draw one line of text into an index buffer.
   * @param {object} target  { w, h, data: Int16Array|Uint8Array }
   */
  function drawText(target, text, x, y, color, scale) {
    const s = scale || 1;
    let cx = x;
    for (const ch of normalize(text)) {
      const g = glyphFor(ch);
      for (let gy = 0; gy < GLYPH_H; gy++)
        for (let gx = 0; gx < GLYPH_W; gx++) {
          if (!g[gy][gx]) continue;
          for (let sy = 0; sy < s; sy++)
            for (let sx = 0; sx < s; sx++) {
              const px = cx + gx * s + sx;
              const py = y + gy * s + sy;
              if (px >= 0 && py >= 0 && px < target.w && py < target.h) target.data[py * target.w + px] = color;
            }
        }
      cx += ADVANCE * s;
    }
  }

  /**
   * Greedy word-wrap. `widthFor(lineIndex)` returns the max pixel width of
   * each line, which lets text follow the rounded top of a headstone.
   * Explicit newlines are kept. Over-long words are hard-broken.
   */
  function wrap(text, widthFor, scale) {
    const s = scale || 1;
    const maxChars = (i) => Math.max(1, Math.floor((widthFor(i) / s + 1) / ADVANCE));
    const lines = [];
    const paragraphs = normalize(text).split(/\r?\n/);
    for (const para of paragraphs) {
      const words = para.trim().split(/\s+/).filter(Boolean);
      if (!words.length) {
        lines.push('');
        continue;
      }
      let line = '';
      for (let word of words) {
        while (true) {
          const limit = maxChars(lines.length);
          const candidate = line ? line + ' ' + word : word;
          if (Array.from(candidate).length <= limit) {
            line = candidate;
            break;
          }
          if (line) {
            lines.push(line);
            line = '';
            continue;
          }
          const chars = Array.from(word);
          lines.push(chars.slice(0, limit).join(''));
          word = chars.slice(limit).join('');
          if (!word) break;
        }
      }
      if (line) lines.push(line);
    }
    while (lines.length && lines[lines.length - 1] === '') lines.pop();
    return lines;
  }

  return { measure, drawText, wrap, normalize, GLYPH_W, GLYPH_H, ADVANCE, LINE_H };
